package ex_08_Switch_Condition;

public class Lab080_InterviewQues {
    public static void main(String[] args) {
        char Code = 'C';
        switch (Code){
            default:
                System.out.println("Helloo");
                break;
            case 'A':
                System.out.println("65");
                break;
            case 'B':
                System.out.println("66");
                break;
        }
    }
}
