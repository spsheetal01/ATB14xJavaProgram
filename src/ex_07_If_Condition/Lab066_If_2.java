package ex_07_If_Condition;

public class Lab066_If_2 {
    public static void main(String[] args) {
        int age = Integer.parseInt(args[0]);
        if (age > 25) {
            System.out.println("Yes you can go to Goa");
        } else {
            System.out.println("Yes you can't go to Goa");

        }
    }
}
