package ex_07_If_Condition;
// multiple condition example
public class Lab_If_ElseIf_Else {
    public static void main(String[] args) {
        int age = 35;
        if(age > 35) {
            System.out.println("age > 35");
        }else if(age < 35) {
            System.out.println("age < 35");
        }else {
            System.out.println("age");
        }
    }
}
